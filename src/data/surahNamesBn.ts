// Convert basic Arabic text to an approximate Bengali phonetic reading aid when user enables pronunciation helper
export function approximateArabicToBengaliPronunciation(arabic: string): string {
  // Clean diacritics slightly for readable phonetic hint while preserving major vowels
  const map: Record<string, string> = {
    'ا': 'আ', 'أ': 'আ', 'إ': 'ই', 'آ': 'আ', 'ب': 'ব', 'ت': 'ত', 'ث': 'ছ',
    'ج': 'জ', 'ح': 'হ', 'خ': 'খ', 'د': 'দ', 'ذ': 'য', 'ر': 'র', 'ز': 'য',
    'س': 'স', 'ش': 'শ', 'ص': 'স', 'ض': 'দ', 'ط': 'ত', 'ظ': 'য', 'ع': 'আ',
    'غ': 'গ', 'ف': 'ফ', 'ق': 'ক', 'ك': 'ক', 'ل': 'ল', 'م': 'ম', 'ن': 'ন',
    'ه': 'হ', 'ة': 'হ', 'و': 'ও', 'ي': 'ই', 'ى': 'আ', 'ء': 'আ',
    'َ': 'া', 'ِ': 'ি', 'ُ': 'ু', 'ْ': '', 'ّ': '', 'ً': 'ান', 'ٍ': 'িন', 'ٌ': 'ুন',
  };
  const words = arabic.trim().split(/\s+/).slice(0, 18);
  return words
    .map((w) => {
      let out = '';
      for (const ch of w) {
        if (map[ch] !== undefined) out += map[ch];
      }
      return out;
    })
    .filter(Boolean)
    .join(' ');
}
